"""Generate Mosquitto password + ACL files from the store config (dev plan §十一).

One MQTT account per device, username = device_id. Each device may only publish/subscribe
its own topics. Usage:
  python tools/gen_mqtt_auth.py --config bycall/custom/banyuexuan/demo_pilot.json --out mosquitto/auth
Outputs: passwd, acl (for Mosquitto) and credentials.json (plain passwords for provisioning
devices; keep it secret, chmod 600). Existing passwords are kept, so re-running after adding a
device does not force re-provisioning of the others.
"""
import argparse
import base64
import hashlib
import json
import os
import secrets
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), '..'))
from bycall.core.config import StoreConfig  # noqa: E402


def mosq_hash(password: str) -> str:
    """Mosquitto 2 password_file format: $7$101$salt$hash (PBKDF2-HMAC-SHA512)."""
    salt = os.urandom(12)
    h = hashlib.pbkdf2_hmac('sha512', password.encode(), salt, 101)
    return '$7$101$%s$%s' % (base64.b64encode(salt).decode(), base64.b64encode(h).decode())


def acl_rules(cfg: StoreConfig):
    """{username: [(access, topic)]}; access is read|write|readwrite."""
    s = cfg.store_id
    rules = {'host': [('readwrite', f'{s}/#')]}
    for room, v in cfg.rooms.items():
        dev = v.get('tablet')
        if not dev:
            continue
        rules[dev] = [('write', f"{s}/call/{v['floor']}/{room}"), ('write', f'{s}/ack/+'),
                      ('write', f'{s}/heartbeat/{dev}'), ('write', f'{s}/status/{dev}'),
                      ('read', f'{s}/feedback/{room}'), ('read', f'{s}/reply/{dev}')]
    for w in set(cfg.watches) | {v.get('watch') for v in cfg.staff.values()}:
        if not w:
            continue
        rules[w] = [('write', f'{s}/ack/+'), ('write', f'{s}/heartbeat/{w}'),
                    ('write', f'{s}/location/{w}'), ('write', f'{s}/vitals/{w}'),
                    ('write', f'{s}/status/{w}'), ('write', f'{s}/watch/{w}'),
                    ('read', f'{s}/dispatch/{w}'), ('read', f'{s}/reply/{w}')]
    rules['station'] = [('read', f'{s}/station/dispatch'), ('read', f'{s}/call/events')]
    return rules


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--config', required=True)
    ap.add_argument('--out', required=True)
    a = ap.parse_args()
    cfg = StoreConfig.load(a.config)
    os.makedirs(a.out, exist_ok=True)
    cred_path = os.path.join(a.out, 'credentials.json')
    creds = json.load(open(cred_path)) if os.path.exists(cred_path) else {}
    rules = acl_rules(cfg)
    for u in rules:
        creds.setdefault(u, secrets.token_urlsafe(18))
    creds = {u: creds[u] for u in rules}          # drop removed devices
    with open(os.path.join(a.out, 'passwd'), 'w') as f:
        f.writelines(f'{u}:{mosq_hash(p)}\n' for u, p in creds.items())
    with open(os.path.join(a.out, 'acl'), 'w') as f:
        f.write('# generated by tools/gen_mqtt_auth.py - do not edit\n')
        for u, rs in rules.items():
            f.write(f'\nuser {u}\n')
            f.writelines(f'topic {acc} {t}\n' for acc, t in rs)
    fd = os.open(cred_path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, 'w') as f:
        json.dump(creds, f, indent=2)
    print(f'{len(creds)} accounts -> {a.out}/ (passwd, acl, credentials.json)')


if __name__ == '__main__':
    main()
